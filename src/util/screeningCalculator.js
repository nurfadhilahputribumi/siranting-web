// ============================================================
// TB/PB/U
// ============================================================

export function calculateTbu(ageMonth, gender, height) {

  if (
    ageMonth === null ||
    gender === null ||
    height === null
  ) {
    return {
      status: "Data tidak tersedia",
      score: 0,
    };
  }

const table =
    gender === 0
        ? ageMonth < 24
            ? femalePbuTable
            : femaleTbuTable
        : ageMonth < 24
            ? malePbuTable
            : maleTbuTable;

  const ref = table[ageMonth];

  if (!ref) {
    return {
      status: "Data tidak tersedia",
      score: 0,
    };
  }

  const [minus3, minus2, plus3] = ref;

  if (height < minus3) {
    return {
      status: "Sangat Pendek (Severely Stunted)",
      score: 3,
    };
  }

  if (height < minus2) {
    return {
      status: "Pendek (Stunted)",
      score: 2,
    };
  }

  if (height <= plus3) {
    return {
      status: "Normal",
      score: 0,
    };
  }

  return {
    status: "Tinggi",
    score: 0,
  };
}


// ============================================================
// BB/U
// ============================================================

export function calculateBbu(ageMonth, gender, weight) {

  if (
    ageMonth === null ||
    gender === null ||
    weight === null
  ) {
    return {
      status: "Data tidak tersedia",
      score: 0,
    };
  }

const table =
    gender === 0
        ? femaleBbuTable
        : maleBbuTable;

  const ref = table[ageMonth];

  if (!ref) {
    return {
      status: "Data tidak tersedia",
      score: 0,
    };
  }

  const [minus3, minus2, plus1] = ref;

  if (weight < minus3) {
    return {
      status:
        "Berat badan sangat kurang (Severely Underweight)",
      score: 3,
    };
  }

  if (weight < minus2) {
    return {
      status:
        "Berat badan kurang (Underweight)",
      score: 2,
    };
  }

  if (weight <= plus1) {
    return {
      status: "Berat badan normal",
      score: 0,
    };
  }

  return {
    status: "Risiko berat badan lebih",
    score: 0,
  };
}


// ============================================================
// TOTAL SCORE
// ============================================================

export function calculateBalitaScore(form) {

  // =========================
  // ANTROPOMETRI
  // =========================

  const tbuResult = calculateTbu(
    form.usiaBayi,
    form.childGender,
    form.tinggiBadan
  );

  const bbuResult = calculateBbu(
    form.usiaBayi,
    form.childGender,
    form.beratBadan
  );


  // =========================
  // SANITASI
  // Masing-masing 0 atau 0.5
  // Maksimal = 2
  // =========================

  const sanitationScore =
    (form.toilet ?? 0) +
    (form.cleanWater ?? 0) +
    (form.homeEnvironment ?? 0) +
    (form.drinkingWater ?? 0);


  // =========================
  // TOTAL SCORE
  // =========================

  const score = [

    // -------------------------
    // FAKTOR IBU
    // -------------------------

    form.usiaIbuHamil ?? 0,
    form.tinggiIbuRisk ?? 0,
    form.pendidikanRisk ?? 0,
    form.jumlahAnakRisk ?? 0,
    form.jarakKelahiran ?? 0,
    form.kek ?? 0,
    form.anemiaIbu ?? 0,
    form.feTablet ?? 0,


    // -------------------------
    // FAKTOR ANAK
    // -------------------------

    form.kelahiranKembar ?? 0,
    form.prematur ?? 0,
    form.birthWeightRisk ?? 0,
    form.shortBirthLength ?? 0,

    form.childGender ?? 0,

    form.imd ?? 0,
    form.exclusiveBreastfeeding ?? 0,
    form.immunization ?? 0,
    form.kenaikanberat ?? 0,
    form.timbangbalita ?? 0,
    form.ukurpanjang ?? 0,

    tbuResult.score,
    bbuResult.score,

    form.vitaminA ?? 0,
    form.anemiaAnak ?? 0,
    form.ispa ?? 0,
    form.pneumonia ?? 0,
    form.diarrhea ?? 0,
    form.parasit ?? 0,
    form.sleepHabit ?? 0,
    form.karbohidrat ?? 0,
    form.proteinHewani ?? 0,


    // -------------------------
    // KELUARGA & SOSIAL EKONOMI
    // -------------------------

    form.jumlahBalitaRumah ?? 0,
    form.income ?? 0,
    form.kiaBook ?? 0,
    form.jkn ?? 0,

    sanitationScore,

    form.handwashing ?? 0,

  ].reduce(
    (total, value) => total + Number(value),
    0
  );


  // =========================
  // KATEGORI RISIKO
  // =========================

  let category;

  if (score <= 15) {
    category = "Risiko Rendah";
  } else if (score <= 31) {
    category = "Risiko Sedang";
  } else {
    category = "Risiko Tinggi";
  }


  return {
    score,
    category,

    tbu: tbuResult.score,
    tbuStatus: tbuResult.status,

    bbu: bbuResult.score,
    bbuStatus: bbuResult.status,
  };
}